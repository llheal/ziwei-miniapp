export function starText(name, field) {
  return STARS[name]?.[field] || PALACE_TEXTS[name]?.[field] || FALLBACK[field] || PALACE_TEXTS_FALLBACK[field] || '';
}

/** 無料で表示する性格の要約 */
export function freeSummary(chart) {
  const stars = chart.soul.majorStars.map((s) => s.name);
  if (stars.length === 0) {
    return { stars: [], keywords: FALLBACK.keywords, text: FALLBACK.short };
  }
  return {
    stars,
    keywords: stars.map((n) => STARS[n]?.keywords).filter(Boolean).join(' / '),
    text: stars.map((n) => starText(n, 'short')).join('\n'),
  };
}

